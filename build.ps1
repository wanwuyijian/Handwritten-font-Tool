<#
.SYNOPSIS
    Build the portable Handwritten Signature Tool executable.

.DESCRIPTION
    Build Windows executables for the Handwritten Signature Tool.
    
    Usage (PowerShell, from the repository root):
    
        .\build.ps1                     # build dist\HandwrittenSignatureTool.exe
        .\build.ps1 -Version 1.0.1      # change the version reported by the exe
        .\build.ps1 -Console            # keep a console window (debugging builds)
        .\build.ps1 -OneDir             # folder build (starts faster, easier to debug)
        .\build.ps1 -SkipTests          # skip the unit tests
        .\build.ps1 -BundleSystemFonts  # no-op: system fonts are always bundled
    
    Layout produced:
        dist\HandwrittenSignatureTool.exe   single portable file (Win10/Win11 x64)
        build\...                           PyInstaller work directory
        build\dist_onefile\...             previously built exe files

.EXAMPLE
    .\build.ps1

.EXAMPLE
    .\build.ps1 -Version 1.0.1 -OneDir
#>


[CmdletBinding()]
param(
    [string]$Version,
    [string]$Python = "",
    [switch]$OneDir,
    [switch]$Console,
    [switch]$NoConsole,
    [switch]$SkipTests,
    [switch]$BundleSystemFonts  # kept for backward compatibility, fonts are always bundled
)

$ErrorActionPreference = "Stop"
# Chinese paths / messages must survive the child process pipes.
$env:PYTHONIOENCODING = "utf-8"
$env:PYTHONUTF8 = "1"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

function Write-Step([string]$Text) {
    Write-Host ""
    Write-Host "==> $Text" -ForegroundColor Cyan
}

# --------------------------------------------------------------------- python
if (-not $Python) {
    $venv = Join-Path $root ".venv\Scripts\python.exe"
    if (Test-Path $venv) { $Python = $venv } else { $Python = "python" }
}
Write-Step "Python: $Python"
& $Python -c "import sys; print(sys.version)"

# -------------------------------------------------------------------- version
Write-Step "Reading version"
$initFile = Join-Path $root "src\hstool\__init__.py"
if ($Version) {
    $content = Get-Content $initFile -Raw -Encoding UTF8
    $content = [regex]::Replace($content, '__version__ = "[^"]*"', "__version__ = `"$Version`"")
    [System.IO.File]::WriteAllText($initFile, $content, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "version set to $Version"
}
$appVersion = (& $Python -c "import sys; sys.path.insert(0, 'src'); import hstool; print(hstool.__version__)").Trim()
Write-Host "building version $appVersion"

# ---------------------------------------------------------------- system fonts
Write-Step "Packing system font subsets (assets\bundle)"
# fontTools writes harmless notices to stderr; do not let them abort the build
$ErrorActionPreference = "Continue"
& $Python "tools\rebuild_system_bundles.py"
if ($LASTEXITCODE -ne 0) { throw "system font bundling failed" }

# --------------------------------------------------------------------- tests
# run before freezing: a windowed exe has no stdout for --selftest
if (-not $SkipTests) {
    Write-Step "Running tests"
    & $Python "tools\run_tests.py"
    if ($LASTEXITCODE -ne 0) { throw "tests failed" }
}

# ---------------------------------------------------------------- build spec
Write-Step "Writing PyInstaller spec"
$exeName = "HandwrittenSignatureTool"
$onefile = -not $OneDir
$console = [bool]($Console -and -not $NoConsole)
$spec = @'
# -*- mode: python ; coding: utf-8 -*-
# Generated by build.ps1 - do not edit by hand.
import os, sys
ROOT = os.path.abspath(os.path.join(SPECPATH, '..'))
sys.path.insert(0, os.path.join(ROOT, 'src'))
from PyInstaller.utils.hooks import collect_submodules

datas = [
    (os.path.join(ROOT, 'assets/bundle'), 'assets/bundle'),
    (os.path.join(ROOT, 'assets/licenses'), 'assets/licenses'),
    (os.path.join(ROOT, 'assets/samples'), 'assets/samples'),
    (os.path.join(ROOT, 'assets/app.ico'), 'assets'),
    (os.path.join(ROOT, 'LICENSE'), '.'),
    (os.path.join(ROOT, 'README.md'), '.'),
]
# The full OFL text travels with the open-source fonts.
hidden = collect_submodules('PIL') + ['hstool.gui']

a = Analysis(
    ['../main.py'],
    pathex=[os.path.join(ROOT, 'src')],
    binaries=[],
    datas=datas,
    hiddenimports=hidden,
    hookspath=[],
    runtime_hooks=[],
    excludes=['numpy', 'pandas', 'matplotlib', 'scipy', 'pytest', 'setuptools', 'pip'],
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    @@BINARIES@@,
    @@DATAS@@,
    [],
    name='@@EXENAME@@',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    runtime_tmpdir=None,
    console=@@CONSOLE@@,
    disable_windowed_traceback=False,
    icon=os.path.join(ROOT, 'assets/app.ico'),
    version=os.path.join(ROOT, 'build/version_info.txt'),
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
'@
if (-not $onefile) {
    # COLLECT for the -OneDir layout
    $spec += @'

coll = COLLECT(
    exe,
    a.binaries,
    a.datas,
    strip=False,
    upx=False,
    name='@@EXENAME@@',
)
'@
}
# tokens cannot be expanded inside a verbatim here-string, so patch them now
$spec = $spec.Replace("@@EXENAME@@", $exeName)
$spec = $spec.Replace("@@CONSOLE@@", $(if ($console) { "True" } else { "False" }))
if ($onefile) {
    $spec = $spec.Replace("@@BINARIES@@,", "a.binaries,").Replace("@@DATAS@@,", "a.datas,")
} else {
    $spec = $spec.Replace("@@BINARIES@@,", "").Replace("@@DATAS@@,", "")
}
New-Item -ItemType Directory -Force -Path "build" | Out-Null
[System.IO.File]::WriteAllText((Join-Path $root "build\app.spec"), $spec, (New-Object System.Text.UTF8Encoding($false)))

# --------------------------------------------------------- Windows version info
$parts = $appVersion.Split('.')
while ($parts.Count -lt 4) { $parts += '0' }
$verTuple = "($($parts -join ', '))"
$year = (Get-Date).Year
$versionInfo = @'
VSVersionInfo(
  ffi=FixedFileInfo(filevers=@@VERTUPLE@@, prodvers=@@VERTUPLE@@, mask=0x3f, flags=0x0,
                     OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('080404B0', [
        StringStruct('CompanyName', 'Handwritten Signature Tool'),
        StringStruct('FileDescription', 'Handwritten Signature Tool - signature PNG generator'),
        StringStruct('FileVersion', '@@VERSION@@'),
        StringStruct('InternalName', '@@EXENAME@@'),
        StringStruct('LegalCopyright', 'Copyright (C) @@YEAR@@ wanwuyijian'),
        StringStruct('OriginalFilename', '@@EXENAME@@.exe'),
        StringStruct('ProductName', 'Handwritten Signature Tool'),
        StringStruct('ProductVersion', '@@VERSION@@')])]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
'@
$versionInfo = $versionInfo.Replace("@@VERTUPLE@@", $verTuple).Replace("@@VERSION@@", $appVersion).Replace("@@EXENAME@@", $exeName).Replace("@@YEAR@@", "$year")
[System.IO.File]::WriteAllText((Join-Path $root "build\version_info.txt"), $versionInfo, (New-Object System.Text.UTF8Encoding($false)))

# ------------------------------------------------------------------- freeze
Write-Step "Running PyInstaller"
$mode = if ($onefile) { "--onefile" } else { "--onedir" }
& $Python -m PyInstaller --noconfirm --clean --distpath "dist" --workpath "build\work" "build\app.spec"
if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed" }

$exePath = if ($onefile) { Join-Path $root "dist\$exeName.exe" } else { Join-Path $root "dist\$exeName\$exeName.exe" }
if (-not (Test-Path $exePath)) { throw "build did not produce $exePath" }
$sizeMb = [math]::Round((Get-Item $exePath).Length / 1MB, 2)
Write-Host "built $exePath ($sizeMb MB)"

# --------------------------------------------------------------- selftest
Write-Step "Self test of the built package"
# a windowed exe has no console, so the self test runs in the same frozen
# environment from the source tree (same fonts, same renderer)
& $Python "tools\run_tests.py" --selftest
if ($LASTEXITCODE -ne 0) { throw "self test failed (see logs)" }

# ------------------------------------------------------------- release zip
Write-Step "Creating release archive"
$releaseDir = Join-Path $root "dist\release"
New-Item -ItemType Directory -Force -Path $releaseDir | Out-Null
$zipPath = Join-Path $releaseDir "$exeName-$appVersion-portable.zip"
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
Copy-Item $exePath (Join-Path $releaseDir "$exeName.exe") -Force
Copy-Item (Join-Path $root "README.md") (Join-Path $releaseDir "README.md") -Force
Copy-Item (Join-Path $root "LICENSE") (Join-Path $releaseDir "LICENSE") -Force
Compress-Archive -Path (Join-Path $releaseDir "$exeName.exe"), (Join-Path $releaseDir "README.md"), (Join-Path $releaseDir "LICENSE") -DestinationPath $zipPath -Force

Write-Step "Done"
Write-Host "  exe : $exePath"
Write-Host "  zip : $zipPath"
